% func that draws deflection of masses part
function   testfill(xv, zv, dv, thv, xm, zm, dm, thm, a, MAXM, refresh, zmax, zmin, Infold);


global Hndl

j=2; % only one fold (1=left, 2=right)

for i = 1:MAXM
   % vocalis masses
   Xv = 1000*[...
      xv(j,i)-dv/2-(Infold.rvoffset(i)/10000)  xv(j,i)-dv/2-(Infold.rvoffset(i)/10000)  xv(j,i)-dv/2-(Infold.rvoffset(i)/10000);...
      xv(j,i)+dv/2                             xv(j,i)-dv/2-(Infold.rvoffset(i)/10000)  xv(j,i)-dv/2-(Infold.rvoffset(i)/10000);...
      xv(j,i)+dv/2                             xv(j,i)-dv/2-(Infold.rvoffset(i)/10000)  xv(j,i)+dv/2                           ;...
      xv(j,i)-dv/2-(Infold.rvoffset(i)/10000)  xv(j,i)-dv/2-(Infold.rvoffset(i)/10000)  xv(j,i)+dv/2];
   Yv = 1000*[...
      (i-1)*a  (i-1)*a 	(i-1)*a;...
      (i-1)*a  i*a		i*a;...
      (i-1)*a  i*a	    i*a;...
      (i-1)*a  (i-1)*a	(i-1)*a];
   Zv = 1000*[... 
      zv(j,i)-thv/2  zv(j,i)-thv/2  zv(j,i)+thv/2;...
      zv(j,i)-thv/2  zv(j,i)-thv/2  zv(j,i)+thv/2;...
      zv(j,i)+thv/2  zv(j,i)+thv/2  zv(j,i)+thv/2; 
      zv(j,i)+thv/2  zv(j,i)+thv/2   zv(j,i)+thv/2];
   % mucosa masses
   Ym = 1000*[...
      (i-1)*a     (i-1)*a 		 (i-1)*a;...
      (i-1)*a      i*a			  	i*a;...
      (i-1)*a      i*a			  	i*a;...
      (i-1)*a     (i-1)*a		 (i-1)*a];
   % muc and voc don't touch
   if (zm(j,i)-thm/2 > zv(j,i)+thv/2)|(xm(j,i)+dm/2 < xv(j,i)-dv/2)
      %		disp('muc and voc don''t touch')
      Xm = 1000*[...
         xm(j,i)-dm/2-(Infold.rmoffset(i)/10000)  xm(j,i)-dm/2-(Infold.rmoffset(i)/10000)  xm(j,i)-dm/2-(Infold.rmoffset(i)/10000) ;...
         xm(j,i)+dm/2                             xm(j,i)-dm/2-(Infold.rmoffset(i)/10000)  xm(j,i)-dm/2-(Infold.rmoffset(i)/10000);...
         xm(j,i)+dm/2                             xm(j,i)-dm/2-(Infold.rmoffset(i)/10000)  xm(j,i)+dm/2;...
         xm(j,i)-dm/2-(Infold.rmoffset(i)/10000)  xm(j,i)-dm/2-(Infold.rmoffset(i)/10000)  xm(j,i)+dm/2];
      Zm = 1000*[...
         zm(j,i)-thm/2  zm(j,i)-thm/2  zm(j,i)+thm/2 ;...
         zm(j,i)-thm/2  zm(j,i)-thm/2  zm(j,i)+thm/2 ;...
         zm(j,i)+thm/2  zm(j,i)+thm/2  zm(j,i)+thm/2 ;...
         zm(j,i)+thm/2  zm(j,i)+thm/2  zm(j,i)+thm/2 ];
      % A) muc touches voc front
   elseif (xm(j,i)+dm/2 >= xv(j,i)-dv/2) & (zm+thm/2 <= zv+thv/2)
      %		disp('A) muc touches voc front')
      Xm = 1000*[...
         xm(j,i)-dm/2-(Infold.rmoffset(i)/10000)  xm(j,i)-dm/2-(Infold.rmoffset(i)/10000)  xm(j,i)-dm/2-(Infold.rmoffset(i)/10000) ;...
         xv(j,i)-dv/2-(Infold.rmoffset(i)/10000)  xm(j,i)-dm/2-(Infold.rmoffset(i)/10000)  xm(j,i)-dm/2-(Infold.rmoffset(i)/10000);... % front part shortened
         xv(j,i)-dv/2-(Infold.rmoffset(i)/10000)  xm(j,i)-dm/2-(Infold.rmoffset(i)/10000)  xm(j,i)+dm/2;... % front part shortened
         xm(j,i)-dm/2-(Infold.rmoffset(i)/10000)  xm(j,i)-dm/2-(Infold.rmoffset(i)/10000)  xm(j,i)+dm/2];
      Zm = 1000*[...
         zm(j,i)-thm/2  zm(j,i)-thm/2  zm(j,i)+thm/2 ;...
         zm(j,i)-thm/2  zm(j,i)-thm/2  zm(j,i)+thm/2 ;...
         zm(j,i)+thm/2  zm(j,i)+thm/2  zm(j,i)+thm/2 ;...
         zm(j,i)+thm/2  zm(j,i)+thm/2  zm(j,i)+thm/2 ];
      % B) muc touches voc top
   elseif (xm(j,i)-dm/2 >= xv(j,i)-dv/2) & (zm-thm/2 <= zv+thv/2)
      %		disp('B) muc touches voc top')
      Xm = 1000*[...
         xm(j,i)-dm/2-(Infold.rmoffset(i)/10000)  xm(j,i)-dm/2-(Infold.rmoffset(i)/10000)  xm(j,i)-dm/2-(Infold.rmoffset(i)/10000) ;...
         xm(j,i)+dm/2  xm(j,i)-dm/2-(Infold.rmoffset(i)/10000)  xm(j,i)-dm/2-(Infold.rmoffset(i)/10000);... % front part shortened
         xm(j,i)+dm/2  xm(j,i)-dm/2-(Infold.rmoffset(i)/10000)  xm(j,i)+dm/2;... % front part shortened
         xm(j,i)-dm/2-(Infold.rmoffset(i)/10000)  xm(j,i)-dm/2-(Infold.rmoffset(i)/10000)  xm(j,i)+dm/2];
      Zm = 1000*[...
         zv(j,i)+thv/2+1e-5  zv(j,i)+thv/2+1e-5  zm(j,i)+thm/2 ;...
         zv(j,i)+thv/2+1e-5  zv(j,i)+thv/2+1e-5  zm(j,i)+thm/2 ;...
         zm(j,i)+thm/2       zm(j,i)+thm/2       zm(j,i)+thm/2 ;...
         zm(j,i)+thm/2       zm(j,i)+thm/2       zm(j,i)+thm/2 ];
      % C) muc is partly in voc in both dimensions
   else
      %		disp('C) muc is partly in voc in both dimensions')
      Xm = 1000*[...
         xm(j,i)-dm/2-(Infold.rmoffset(i)/10000)  xm(j,i)-dm/2-(Infold.rmoffset(i)/10000)  xm(j,i)-dm/2-(Infold.rmoffset(i)/10000) ;...
         xm(j,i)+dm/2                             xm(j,i)-dm/2-(Infold.rmoffset(i)/10000)  xm(j,i)-dm/2-(Infold.rmoffset(i)/10000);...
         xm(j,i)+dm/2                             xm(j,i)-dm/2-(Infold.rmoffset(i)/10000)  xm(j,i)+dm/2;...
         xm(j,i)-dm/2-(Infold.rmoffset(i)/10000)  xm(j,i)-dm/2-(Infold.rmoffset(i)/10000)  xm(j,i)+dm/2];
      Zm = 1000*[...
         zv(j,i)+thv/2+1e-4  zm(j,i)-thm/2  zm(j,i)+thm/2 ;...
         zv(j,i)+thv/2+1e-4  zm(j,i)-thm/2  zm(j,i)+thm/2 ;...
         zm(j,i)+thm/2       zm(j,i)+thm/2  zm(j,i)+thm/2 ;...
         zm(j,i)+thm/2       zm(j,i)+thm/2  zm(j,i)+thm/2 ];
   end % of if touch

   tcolor(1,1,1:3) = [.5 .5 .5];
   if refresh
      for ii = 1:size(Xv,2)
         set(Hndl.plotmassrec21(i,ii), 'XData', Xv(:,ii));
         set(Hndl.plotmassrec21(i,ii), 'YData', Yv(:,ii));
         set(Hndl.plotmassrec21(i,ii), 'ZData', Zv(:,ii));
      end
   else
      %  	hold on
      Hndl.plotmassrec21(i,:) = fill3(Xv,Yv,Zv,tcolor);
   end
   tcolor(1,1,1:3) = [.7 .7 .7];
   if refresh
      for ii = 1:size(Xm,2) % for each face
         set(Hndl.plotmassrec22(i,ii), 'XData', Xm(:,ii));
         set(Hndl.plotmassrec22(i,ii), 'YData', Ym(:,ii));
         set(Hndl.plotmassrec22(i,ii), 'ZData', Zm(:,ii));
      end
   else
      Hndl.plotmassrec22(i,:) = fill3(Xm,Ym,Zm,tcolor);
      %		rectangle('Position',[-1/2*a*1000, zmin, ...
      %		1/2*a*1000, zmax-zmin], 'FaceColor', [0.4 0.4 0.4], ...
      %		'Parent', Hndl.plotmassax2);

      axis([0 3 0 15 -2 3]);
      view(3)
      xlabel('x [mm]')
      ylabel('y [mm]')
      zlabel('z [mm]')
      %    drawnow
      %    hold off
   end % of if refresh
end % of for i = 1:MAXM
